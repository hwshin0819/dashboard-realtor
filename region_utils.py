def ordered_short_regions(full_names) -> list:
    """데이터에 실제로 존재하는 지역만, 레퍼런스 순서대로 짧은 이름으로 반환."""
    present = set(full_names)
    return [short for short in REGION_ORDER if FULL_NAME.get(short) in present]


def normalize_sido(ld_code_nm: str) -> str:
    """시군구명 전체 문자열에서 시도 이름만 추출. legacy(realtor) 데이터의 시도 표기와 맞춘다."""
    if not ld_code_nm:
        return "기타"
    tokens = ld_code_nm.split()
    first = tokens[0]
    if first == "전남광주통합특별시":
        second = tokens[1] if len(tokens) > 1 else ""
        return "광주광역시" if second.startswith(GWANGJU_GU) else "전라남도"
    return first
